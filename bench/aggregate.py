"""Collect bench/dl, bench/runs -> bench/results.json + results.md"""
import json, os, sys, glob, statistics as st
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
B = os.path.join(ROOT, "bench")
DAYS = os.environ.get("DOPP_DAYS", os.path.join(ROOT, "data", "days"))
C = json.load(open(f"{B}/candidates.json"))
AUD = json.load(open(f"{B}/audio_labels.json")) if os.path.exists(f"{B}/audio_labels.json") else {}
def L(p):
    return json.load(open(p)) if os.path.exists(p) else None
MODES = ["blind", "prior", "prior_single", "blind_wind", "prior_wind"]
clips = []
for c in C:
    cid = c["id"]; dl = L(f"{B}/dl/{cid}.json"); prep = L(f"{B}/runs/{cid}_prep.json")
    r = dict(id=cid, place=c["location_name"], tier=c["truth_tier"], radius_m=c["location_uncertainty_m"], day=c["utc_start"][:10],
             region="Europe" if c["lon"] > -30 else "CONUS", prior_s=c["prior_uncertainty_s"],
             download=(dl or {}).get("status", "not_attempted"), download_source=(dl or {}).get("source"),
             download_error=((dl or {}).get("err") or "")[-300:] or None)
    a = AUD.get(cid, {})
    r["audio"] = a.get("label") if a else (None if not prep else "unlabelled")
    r["audio_note"] = a.get("note")
    if prep:
        r["screen"] = prep["screen"]; r["n_events"] = prep["n_events"]; r["n_primary"] = prep["n_primary"]
        r["selected_events"] = [e for e in prep["events"] if e["id"] in prep["selected"]]
    r["runs"] = {}
    for m in MODES:
        x = L(f"{B}/runs/{cid}_{m}.json")
        if x: r["runs"][m] = {k: x.get(k) for k in ("status", "reason", "error", "search_mode", "elapsed_s", "sc", "pipeline", "top5", "job_id", "events")}
    # failure classification per mode
    for m, x in r["runs"].items():
        s = x.get("sc") or {}
        if x["status"] == "timeout" or (x.get("elapsed_s") or 0) > 1800: f = "too_slow_timeout"; x["sc"] = None
        elif x["status"] == "not_runnable": f = "not_runnable_blind_single"
        elif x["status"] == "no_events": f = "no_events_detected"
        elif x["status"] == "oom" or (x["status"] == "error" and not x.get("error")): f = "out_of_memory"
        elif x["status"] == "not_run": f = "not_run_time_budget"
        elif x["status"] == "error": f = "error"
        elif x["status"] != "ok": f = "no_candidate_survived_filters"
        elif s.get("truth_rank") == 1: f = None
        else: f = "wrong_top_match"
        x["failure"] = f
    clips.append(r)

def stage(r):
    if r["download"] != "ok": return "download_blocked"
    if r["audio"] in ("no_live_audio", "unusable_audio"): return r["audio"]
    if not r.get("n_primary"): return "no_events_detected"
    return "ran"

summ = dict(candidates=len(clips), downloaded=sum(r["download"] == "ok" for r in clips),
            usable_audio=sum(r["download"] == "ok" and r["audio"] == "live_audio" for r in clips),
            events_found=sum(r["download"] == "ok" and r["audio"] == "live_audio" and (r.get("n_primary") or 0) > 0 for r in clips),
            two_plus_events=sum(r["download"] == "ok" and r["audio"] == "live_audio" and len(r.get("selected_events") or []) >= 2 for r in clips))
summ["stage_counts"] = {}
for r in clips: summ["stage_counts"][stage(r)] = summ["stage_counts"].get(stage(r), 0) + 1
for m in MODES:
    rr = [r for r in clips if stage(r) == "ran" and m in r["runs"]]
    if not rr: continue
    ranks = [(r["runs"][m].get("sc") or {}).get("truth_rank") for r in rr]
    d = [(r["runs"][m].get("sc") or {}).get("top1_dist_m") for r in rr]; d = [x for x in d if x is not None]
    fails = {}
    for r in rr:
        f = r["runs"][m]["failure"]
        if f: fails[f] = fails.get(f, 0) + 1
    summ[m] = dict(n=len(rr), top1=sum(1 for k in ranks if k and k <= 1), top3=sum(1 for k in ranks if k and k <= 3),
                   top10=sum(1 for k in ranks if k and k <= 10), median_top1_km=round(st.median(d) / 1000, 2) if d else None,
                   worst_top1_km=round(max(d) / 1000, 1) if d else None, failures=fails,
                   median_elapsed_s=round(st.median([r["runs"][m].get("elapsed_s") or 0 for r in rr])))
json.dump(dict(summary=summ, clips=clips), open(f"{B}/results.json", "w"), indent=1)

# markdown
def km(x): return "" if x is None else f"{x/1000:.1f}"
lines = ["# Outdoor-video benchmark results", "", "Generated by `bench/aggregate.py` from `bench/runs/`. Ground truth (location, time) is used only for scoring.",
         "Hit = a result within truth radius + 500 m. blind = date only, whole-day store (CONUS / Europe); prior = stream-metadata start time +- prior_uncertainty_s.", "",
         "## Funnel", "", f"candidates {summ['candidates']} -> downloaded {summ['downloaded']} -> usable live audio {summ['usable_audio']} -> events found {summ['events_found']} (>=2 events: {summ['two_plus_events']})", "",
         "Stage counts: " + ", ".join(f"{k} {v}" for k, v in summ["stage_counts"].items()), "", "## Hit rates", "",
         "| mode | n | top-1 | top-3 | top-10 | median top-1 err (km) | worst (km) | median runtime (s) | failures |", "|---|---|---|---|---|---|---|---|---|"]
for m in MODES:
    if m in summ:
        s = summ[m]; lines.append(f"| {m} | {s['n']} | {s['top1']} | {s['top3']} | {s['top10']} | {s['median_top1_km']} | {s['worst_top1_km']} | {s['median_elapsed_s']} | " +
                                  ", ".join(f"{k} {v}" for k, v in s["failures"].items()) + " |")
lines += ["", "## Per clip", "", "| clip | dl | audio | events (primary) | blind: mode / rank / top-1 km / margin / s | prior: mode / rank / top-1 km / margin / s | notes |", "|---|---|---|---|---|---|---|"]
def cell(x):
    if not x: return ""
    s = x.get("sc") or {}
    if x["status"] != "ok": return f"{x.get('search_mode') or ''} {x['status']}"
    mg = s.get("margin"); return f"{x['search_mode']} / {s.get('truth_rank') or '-'} / {km(s.get('top1_dist_m'))} / {'' if mg is None else f'{100*mg:.1f}%'} / {round(x.get('elapsed_s') or 0)}"
for r in clips:
    lines.append(f"| {r['id']} | {r['download']} | {r['audio'] or ''} | {r.get('n_events','')} ({r.get('n_primary','')}) | {cell(r['runs'].get('blind'))} | {cell(r['runs'].get('prior'))} | {r.get('audio_note') or ''} |")
open(f"{B}/results.md", "w").write("\n".join(lines) + "\n")
print(json.dumps(summ, indent=1))
